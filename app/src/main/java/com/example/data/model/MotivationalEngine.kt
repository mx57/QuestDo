package com.example.data.model

import java.util.Calendar

data class MotivationalMessage(
    val quote: String,
    val authorOrTip: String,
    val category: String
)

object MotivationalEngine {

    fun getContextualQuote(mood: MoodType): MotivationalMessage {
        val hour = Calendar.getInstance().get(Calendar.HOUR_OF_DAY)
        val timePeriod = when (hour) {
            in 5..11 -> "утро"
            in 12..17 -> "день"
            in 18..22 -> "вечер"
            else -> "ночь"
        }

        return when (mood) {
            MoodType.FOCUS -> when (timePeriod) {
                "утро" -> MotivationalMessage(
                    "«Утро определяет день. Выбери главное действие до того, как мир потребует твоего внимания.»",
                    "Принцип Глубокой Работы",
                    "Фокус"
                )
                "день" -> MotivationalMessage(
                    "«Фокус — это не просто сказать «да» одной задаче. Это смелость сказать «нет» сотне других.»",
                    "Стив Джобс",
                    "Концентрация"
                )
                "вечер" -> MotivationalMessage(
                    "«Очисти разум от незавершенных петель. Закрой текущий уровень и подари себе спокойный вечер.»",
                    "Кэл Ньюпорт",
                    "Завершение"
                )
                else -> MotivationalMessage(
                    "«Ночные часы тихи, но сон — лучший инструмент перезагрузки мозга. Закрой один шаг и ложись отдыхать.»",
                    "Нейробиология сна",
                    "Перезагрузка"
                )
            }
            MoodType.CALM -> when (timePeriod) {
                "утро" -> MotivationalMessage(
                    "«Не торопись. Спокойная река преодолевает любые скалы. Один вдох, одно плавное действие.»",
                    "Дзен-философия",
                    "Спокойствие"
                )
                "день" -> MotivationalMessage(
                    "«Тревога исчезает там, где начинается маленькое конкретное действие. Дыши ровно.»",
                    "Осознанность",
                    "Антистресс"
                )
                "вечер" -> MotivationalMessage(
                    "«Ты сделал(а) всё, что мог(ла) сегодня. Отпусти тревоги прошедшего дня.»",
                    "Медитация баланса",
                    "Мир внутри"
                )
                else -> MotivationalMessage(
                    "«Тьма за окном напоминает: миру нужен твой покой. Замедли дыхание.»",
                    "Ночной покой",
                    "Релакс"
                )
            }
            MoodType.OVERCOME -> when (timePeriod) {
                "утро" -> MotivationalMessage(
                    "«Дисциплина — это мост между твоими мечтами и твоими достижениями. Время сокрушать препятствия!»",
                    "Кодекс Воина",
                    "Энергия"
                )
                "день" -> MotivationalMessage(
                    "«Боль дисциплины весит граммы, боль сожаления — тонны. Жми вперед, уровень почти пройден!»",
                    "Джим Рон",
                    "Напор"
                )
                "вечер" -> MotivationalMessage(
                    "«Победа куется в мелочах. Гордись сегодняшней битвой и приготовься к новым победам.»",
                    "Стоицизм",
                    "Триумф"
                )
                else -> MotivationalMessage(
                    "«Настоящий характер закаляется, когда никто не видит. Но помни: отдых — часть стратегии.»",
                    "Марк Аврелий",
                    "Стойкость"
                )
            }
            MoodType.CARE -> when (timePeriod) {
                "утро" -> MotivationalMessage(
                    "«Будь добр(а) к себе сегодня. Твоя ценность не измеряется только количеством галочек.»",
                    "Брене Браун",
                    "Самосострадание"
                )
                "день" -> MotivationalMessage(
                    "«Выпей воды, расправь плечи, сделай мягкий вдох. Ты делаешь огромную работу.»",
                    "Забота о теле",
                    "Мягкость"
                )
                "вечер" -> MotivationalMessage(
                    "«Ты заслуживаешь теплого отдыха, уютного чая и добрых мыслей. Поблагодари себя за сегодня.»",
                    "Теплый вечер",
                    "Уют"
                )
                else -> MotivationalMessage(
                    "«Укутайся пледом и позволь телу расслабиться. Ты в безопасности, дела подождут до утра.»",
                    "Забота перед сном",
                    "Нежность"
                )
            }
        }
    }

    val antiProcrastinationTips = listOf(
        Pair("Правило 2 минут", "Если следующий шаг квеста занимает меньше 2 минут — начни его прямо сейчас, не думая о результате."),
        Pair("Правило 5 секунд", "Посчитай: 5... 4... 3... 2... 1... и физически сделай первое микро-движение (открой документ, встань с дивана)."),
        Pair("Микро-шаг", "Слишком тяжело начать? Сделай действие «на троечку»: напиши 1 строчку, прочитай 1 абзац, положи 1 вещь."),
        Pair("Дыхание 4-7-8", "Вдох на 4 секунды через нос, задержка дыхания на 7 секунд, долгий выдох через рот на 8 секунд. Тревога отступит."),
        Pair("Легальный отказ от перфекционизма", "Сделанное несовершенно лучше, чем идеальное, существующее только в фантазиях.")
    )
}

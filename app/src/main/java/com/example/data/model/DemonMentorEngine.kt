    fun getDemonContextualQuote(): MotivationalMessage {
        val hour = Calendar.getInstance().get(Calendar.HOUR_OF_DAY)
        val quoteText = when (hour) {
            in 5..11 -> MORNING_ROASTS.random()
            in 12..17 -> AFTERNOON_ROASTS.random()
            in 18..22 -> EVENING_ROASTS.random()
            else -> NIGHT_ROASTS.random()
        }
        return MotivationalMessage(
            quote = "«$quoteText»",
            authorOrTip = "Люцик • Адский Наставник 😈",
            category = "Адский Пинoк 🔥"
        )
    }

